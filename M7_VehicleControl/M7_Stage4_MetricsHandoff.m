    simulationTime, ...
    vehicleStates(:,4), ...
    "LineWidth",2)

hold on

plot( ...
    simulationTime, ...
    speedCommands, ...
    "--", ...
    "LineWidth",2)

legend( ...
    "Actual Speed", ...
    "Commanded Speed", ...
    "Location","best")

title("Vehicle Speed")
xlabel("Time [seconds]")
ylabel("Speed [m/s]")
